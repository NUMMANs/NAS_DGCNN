def pareto_policy(room_stats: Dict[str, object]) -> Union[str, int, Dict, List]:
    """
    在"精度 × 成本"之间选一个架构。

    ⚠⚠ **教训：这一层不该用 LLM 来做选择**
    ================================================
    候选池是**有限的**（~70 个已实测配置），目标函数是**确定的**
    （`combined = mIoU − 0.02·log10(cost/103.8)`）。
    在有限集上求确定目标的最优 → **枚举就是精确解**，确定性、瞬时、且保证最优。

    实测印证：两轮各 60 迭代的 LLM 搜索，best 都出现在**早期迭代**，
    最终 best = 0.4216 —— **还不如直接枚举出来的 0.4244**。

    **正确分工**：LLM 用于**提出**新架构（`nas_ptseg/arch_loop.py`，空间 3.2×10^8，枚举不了）；
    **选择**最优用枚举（`python -m nas_ptseg.pareto_select`）。
    LLM 的价值在"提出"，不在"选择"。

    这里直接返回**枚举出来的精确最优**（`voxel15_z16,voxel20_z32,voxel50_z96@gate`，
    combined 0.4244，比旧的 `ms3_mix_v20_v50_z16_z32_z96` 高 0.0028），
    让搜索从一个正确的位置起步，而不是从我手填的一个坏基线起步。
    """
    return "voxel15_z16,voxel20_z32,voxel50_z96@gate"


