"""被进化的程序（**精度 × 成本 双目标**）：选一个几何架构。

背景（为什么是"选架构"而不是"按房间调架构"）
================================================================
本项目已实测两条否定性结论：
  1. k 轴榨干：逐房间 oracle 的 headroom 仅 +0.0017（< σ_fit 0.0014）
  2. 架构轴零交互：逐房间 oracle = 最好单一配置；6 个 Area 的最优配置**全部相同**
     → 「按房间/按域条件化架构」拿不到收益

同时测到一条**正面**结论：
  3. 换几何表示能同时改变精度与成本，差异达 20~30 倍：
       `voxel25_z64`  mIoU 0.3885   15.9 ms/step   424 MiB
       `points`       mIoU 0.3370  104.2 ms/step  3524 MiB
     → 「精度 × 成本」第一次有真实的差异可探索

所以这个程序的**有效自由度是"选哪一个架构"**（一个离散选择），
它的价值不在"条件化"，而在**在 Pareto 前沿上挑到一个好点**。

要进化的函数
================================================================
    pareto_policy(room_stats) -> 候选下标 | 架构名 | 配置 dict | 上述的列表

`room_stats` 目前只给全局信息（本项目已证明按房间分化无收益），
真正要学的是**在精度与成本之间怎么取舍**。

⚠ 不要试图识别具体房间（没有房间号/Area 可用，也不该用）。
"""

from typing import Dict, List, Union


